def main():
    apply_ = '--apply' in sys.argv
    note = GisaEssayNote.objects.get(certification__name='식물보호기사', slug='topics')
    text = note.content

    # 1) 이미 있는 주제 — 회차 수와 출제 목록에 2026-1 을 더한다
    for key, newfreq in BUMP.items():
        m = re.search(r'^## (\d+)회 · ([^\n·]+) · (.+)\n\n\*\*출제\*\* (.+)\n'
                      r'\*\*주제키\*\* %s$' % key, text, flags=re.M)
        if not m:
            print(f'노트에서 못 찾음: {key}')
            return 1
        if '2026-1' in m.group(4):
            print(f'이미 반영됨: {key}')
            continue
        head = ('## %d회 · %s · %s\n\n**출제** 2026-1 %s\n**주제키** %s'
                % (newfreq, m.group(2), m.group(3), m.group(4), key))
        text = text.replace(m.group(0), head)
        print(f'{key} {m.group(1)}회 → {newfreq}회  {m.group(3)[:34]}')

    # 2) 신규 주제 — 없을 때만 덧붙인다
    added = []
    for key in re.findall(r'^\*\*주제키\*\* ([0-9a-f]+)$', NEW, flags=re.M):
        if key not in text:
            added.append(key)
    if added:
        text = text.rstrip() + '\n' + NEW.rstrip() + '\n'
    print('신규 주제 추가:', len(added), '개', added)

    # 3) 머리말의 모수 갱신
    text = text.replace(
        '2023~2025년 기출 **시험지 18장**(기사 9 · 산업기사 9)을 주제로 묶어, 두 시험지 이상에\n'
        '나온 **51주제**마다',
        '2023~2026년 기출 **시험지 19장**(기사 10 · 산업기사 9)을 주제로 묶어, 두 시험지 이상에\n'
        '나온 주제와 2026-1회 신규 주제마다')
    text = text.replace('18회(배액 계산)와\n17회(농약 종류 가려내기)',
                        '19회(배액 계산)와\n18회(농약 종류 가려내기)')

    # 4) 주제키가 DB 와 맞는지 대조한다 — 어긋나면 엉뚱한 문항에 글이 붙는다
    bad = []
    for key in re.findall(r'^\*\*주제키\*\* ([0-9a-f]+)$', text, flags=re.M):
        if not GisaEssayQuestion.objects.filter(topic_key=key).exists():
            bad.append(key)
    if bad:
        print('DB 에 없는 주제키:', bad)
        return 1

    print(f'\n{len(note.content):,}자 → {len(text):,}자')
    if not apply_:
        print('(검증만 했다. --apply 를 붙여야 DB 에 들어간다)')
        return 0
    note.content = text
    note.save(update_fields=['content', 'updated_at'])
    print('반영했다.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
