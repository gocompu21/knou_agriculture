def pl(pts, w=0.25, c=INK, dash=None, close=False, fill='none', cap='round'):
    d = 'M' + ' L'.join(f'{x:g} {y:g}' for x, y in pts) + (' Z' if close else '')
    A(f'<path d="{d}" fill="{fill}" stroke="{c}" stroke-width="{w}" stroke-linejoin="round" stroke-linecap="{cap}"'
      + (f' stroke-dasharray="{dash}"' if dash else '') + '/>')


def smooth(pts, close=False):
    """Catmull-Rom → 3차 베지어."""
    P = list(pts)
    n = len(P)
    g = (lambda i: P[i % n]) if close else (lambda i: P[min(max(i, 0), n - 1)])
    d = f'M{P[0][0]:g} {P[0][1]:g}'
    for i in range(n if close else n - 1):
        p0, p1, p2, p3 = g(i - 1), g(i), g(i + 1), g(i + 2)
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f' C{c1[0]:.2f} {c1[1]:.2f} {c2[0]:.2f} {c2[1]:.2f} {p2[0]:g} {p2[1]:g}'
    return d + (' Z' if close else '')


def curve(pts, w=0.22, c=INK, dash=None, off=None):
    A(f'<path d="{smooth(pts)}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round"'
      + (f' stroke-dasharray="{dash}"' if dash else '')
      + (f' stroke-dashoffset="{off}"' if off is not None else '') + '/>')


def text(x, y, s, size=2.3, c=INK, anchor='middle', weight=500, rot=None):
    tr = f' transform="rotate({rot} {x} {y})"' if rot else ''
    A(f'<text x="{x:g}" y="{y:g}" font-size="{size}" fill="{c}" text-anchor="{anchor}" font-weight="{weight}"{tr}>{s}</text>')


def scallop_d(pts, r=1.0, side=1):
    """폴리라인을 따라 반원 물결(수림 경계)을 그리는 path d. 채색 면도 **이 길을 그대로 경계로 쓴다** —
    기준선(직선)으로 칠하면 반원이 면 밖으로 삐져나와 경계가 어긋난다.
    거꾸로 이을 때는 점 순서를 뒤집고 side 도 뒤집어야 같은 쪽으로 부푼다."""
    res = [pts[0]]
    for a, b in zip(pts, pts[1:]):
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        k = max(1, round(L / (2 * r)))
        res += [(a[0] + (b[0] - a[0]) * i / k, a[1] + (b[1] - a[1]) * i / k) for i in range(1, k + 1)]
    d = f'M{res[0][0]:.2f} {res[0][1]:.2f}'
    for a, b in zip(res, res[1:]):
        rr = math.hypot(b[0] - a[0], b[1] - a[1]) / 2
        d += f' A{rr:.2f} {rr:.2f} 0 0 {1 if side > 0 else 0} {b[0]:.2f} {b[1]:.2f}'
    return d


def scallops(pts, r=1.0, w=0.24, side=1):
    A(f'<path d="{scallop_d(pts, r, side)}" fill="none" stroke="{INK}" stroke-width="{w}" stroke-linecap="round"/>')


