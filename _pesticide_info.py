def main():
    apply_ = '--apply' in sys.argv
    rows = json.load(io.open('_pesticide_cards.json', encoding='utf-8'))
    names = {r['name'] for r in rows}

    miss = sorted(names - set(INFO))
    extra = sorted(set(INFO) - names)
    if miss:
        print('정보가 없는 농약 %d종: %s' % (len(miss), miss))
    if extra:
        print('카드에 없는 이름 %d개: %s' % (len(extra), extra))
    if miss or extra:
        return 1

    longest = max(INFO.items(), key=lambda kv: len(kv[1][1]))
    for r in rows:
        fam, act, tgt = INFO[r['name']]
        r['family'], r['action'], r['target'] = fam, act, tgt

    print('%d종에 계열·작용기작·주요대상을 채웠다.' % len(rows))
    print('작용기작이 가장 긴 것: %s (%d자)' % (longest[0], len(longest[1][1])))
    from collections import Counter
    c = Counter(r['family'] for r in rows)
    print('계열 %d가지 · 많은 것: %s' % (
        len(c), ', '.join('%s %d' % kv for kv in c.most_common(5))))

    if not apply_:
        print('(검증만 했다. --apply 를 붙여야 파일을 고친다)')
        return 0
    io.open('_pesticide_cards.json', 'w', encoding='utf-8').write(
        json.dumps(rows, ensure_ascii=False, indent=1) + '\n')
    print('고쳤다: _pesticide_cards.json')
    return 0


if __name__ == '__main__':
    sys.exit(main())
