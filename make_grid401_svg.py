def text(x, y, s, size=1.7, c=INK, anchor='middle', weight=600, rot=None, under=False):
    tr = f' transform="rotate({rot} {x} {y})"' if rot else ''
    A(f'<text x="{x:g}" y="{y:g}" font-size="{size}" fill="{c}" text-anchor="{anchor}" font-weight="{weight}"{tr}>{s}</text>')
    if under:
        w = len(s) * size * 0.62
        pl([(x - w / 2, y + 0.7), (x + w / 2, y + 0.7)], 0.22)


def rot_rect(cx, cy, w, h, deg, label=None):
    a = math.radians(deg)
    ca, sa = math.cos(a), math.sin(a)
    pts = [(cx + dx * ca - dy * sa, cy + dx * sa + dy * ca) for dx, dy in
           ((-w / 2, -h / 2), (w / 2, -h / 2), (w / 2, h / 2), (-w / 2, h / 2))]
    pl(pts, 0.2, close=True, fill='#fff')
    if label:
        A(f'<text x="{cx:g}" y="{cy + 0.55:g}" font-size="1.5" fill="{INK}" text-anchor="middle" font-weight="700" '
          f'transform="rotate({deg} {cx} {cy})">{label}</text>')


