def scallops(pts, r=1.0, w=0.2, side=1):
    """폴리라인을 따라 반원 물결(수림 경계). side=1 이면 진행 방향 왼쪽으로 부푼다."""
    # 일정 간격으로 다시 나눈다
    res = [pts[0]]
    for a, b in zip(pts, pts[1:]):
        L = math.hypot(b[0] - a[0], b[1] - a[1])
        k = max(1, round(L / (2 * r)))
        res += [(a[0] + (b[0] - a[0]) * i / k, a[1] + (b[1] - a[1]) * i / k) for i in range(1, k + 1)]
    d = f'M{res[0][0]:.2f} {res[0][1]:.2f}'
    for a, b in zip(res, res[1:]):
        rr = math.hypot(b[0] - a[0], b[1] - a[1]) / 2
        d += f' A{rr:.2f} {rr:.2f} 0 0 {1 if side > 0 else 0} {b[0]:.2f} {b[1]:.2f}'
    A(f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="{w}" stroke-linecap="round"/>')

