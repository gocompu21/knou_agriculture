def main():
    done = skip = 0
    for key, ref in REF.items():
        name, y, r, n = key
        q = GisaEssayQuestion.objects.filter(
            certification__name=name, year=y, round=r, number=n).first()
        if not q:
            print(f'!! 문항 없음: {name} {y}-{r} {n}번')
            continue
        if (q.reference or '').strip() == ref.strip():
            skip += 1
            continue
        done += 1
        old = len(q.reference or '')
        print(f'  {name} {y}-{r} {n}번  {old}자 → {len(ref)}자')
        if APPLY:
            q.reference = ref
            q.save(update_fields=['reference'])
    print(f'\n{done}건' + (' 반영했다.' if APPLY else ' (미반영 — --apply 로 넣는다)')
          + (f' / 이미 같은 것 {skip}건' if skip else ''))


if __name__ == '__main__':
    main()
