# ── Sorensen 군집계수 2회 ────────────────────────────────────────
# 종수가 달라 값이 갈린다(30·20·5 → 0.2 / 30·40·20 → 0.57).
def _sor(a, b, c):
    v = 2 * c / (a + b)
    return [
        "계산)\n"
        "Sorensen 계수는 공통 종수를 두 배 하여 **두 군집 종수의 합**으로 나눈다.\n"
        "[eq]Sorensen = 2c / (a + b)[/eq]\n"
        "a : A군집 종수, b : B군집 종수, c : 공통 종수\n"
        "값을 대입한다.\n"
        "[eq]= (2 × %d) / (%d + %d) = %d / %d = **%s**[/eq]"
        % (c, a, b, 2 * c, a + b, f'{v:.4f}'.rstrip('0').rstrip('.')),
        # 딱 떨어지면 '약'을 붙이지 않는다 (0.2 는 근사값이 아니다)
        "답) %s" % (f'{v:g}' if round(v, 4) == round(v, 2)
                    else '약 %.2f' % v),
    ]


