# ── 경사도 2회 ───────────────────────────────────────────────────
# 표고차가 다르다(10m vs 20m). 축척 환산 → 경사도 순서를 맞춘다.
def _slope(dh, scale, cm, pct):
    return [
        "계산)\n"
        "도상거리를 축척으로 실제 거리로 바꾼 뒤 표고차와 나눈다.\n"
        "[eq]실제 수평거리 = 도상거리 × 축척분모\n"
        "  = %scm × %s = %s,000cm = **%sm**[/eq]\n"
        "[eq]경사도 = 수직거리 / 수평거리 × 100\n"
        "  = %s / %s × 100 = **%s%%**[/eq]"
        % (cm, scale, cm * scale // 1000, cm * scale // 100,
           dh, cm * scale // 100, pct),
        "답) 경사도 %s%%" % pct,
    ]


FIX[(2024, 1, 10)] = _slope(10, 500, 10, 20)
FIX[(2008, 4, 12)] = _slope(20, 500, 10, 40)

