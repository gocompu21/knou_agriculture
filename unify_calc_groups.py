def main():
    apply = '--apply' in sys.argv
    n = 0
    for (year, rnd, num), items in sorted(FIX.items(), reverse=True):
        q = Q.objects.filter(source='기출', year=year, round=rnd,
                             number=num, qtype='계산').first()
        if not q:
            print(f'  없음 {year}-{rnd} #{num}')
            continue
        if q.answer_items == items and not q.answer_text:
            continue
        n += 1
        print(f'  {year}-{rnd} #{num}')
        if apply:
            q.answer_items = items
            q.answer_text = ''
            q.save(update_fields=['answer_items', 'answer_text'])
    print(f'{"반영" if apply else "대상"} {n}건 / 전체 {len(FIX)}건')
    if not apply:
        print('(--apply 로 반영)')


if __name__ == '__main__':
    main()
