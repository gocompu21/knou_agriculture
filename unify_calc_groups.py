# ── 개체군 생장률(생존율) 4회 ────────────────────────────────────
# 2020-3 만 수치가 다르다(출생 0.8·이입 0.2). 전개는 같게 두고 값만 바꾼다.
def _growth(b, i, d, e):
    return [
        "계산)\n"
        "개체군을 늘리는 요인은 출생과 이입, 줄이는 요인은 사망과 이출이다.\n"
        "[eq]생장률 = (출생률 + 이입률) − (사망률 + 이출률)[/eq]\n"
        "값을 대입한다.\n"
        # 두 줄 모두 = 로 시작하므로 들여쓰기 없이 같은 자리에 맞춘다
        "[eq]= (%s + %s) − (%s + %s)\n"
        "= %.1f − %.1f = **%s**[/eq]"
        % (b, i, d, e, b + i, d + e, f'{b + i - d - e:g}'),
        "답) %s" % f'{b + i - d - e:g}',
    ]


FIX[(2023, 3, 3)] = _growth(0.7, 0.3, 0.1, 0.1)
FIX[(2017, 3, 1)] = _growth(0.7, 0.3, 0.1, 0.1)
