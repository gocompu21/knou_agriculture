def shannon(base, a_val, b_val, single=None):
    """Shannon 지수 — 로그 밑만 회차마다 다르고 전개는 같다."""
    if single:                       # 2014-2 처럼 군집 하나만 묻는 해
        return single
    lg, la, lb = base
    return [
        "계산)\n"
        "Shannon-Wiener 종다양성지수는 각 종의 상대풍부도 pᵢ로 구한다.\n"
        "[eq]H′ = −Σ pᵢ %s pᵢ[/eq]\n"
        "두 군집 모두 총 개체수가 16이므로 pᵢ는 다음과 같다.\n"
        "| 종 | A군집 | pᵢ | B군집 | pᵢ |\n"
        "|----|----|----|----|----|\n"
        "| 종1 | 4 | 0.25 | 4 | 0.25 |\n"
        "| 종2 | 4 | 0.25 | 4 | 0.25 |\n"
        "| 종3 | 8 | 0.50 | 4 | 0.25 |\n"
        "| 종4 | 0 | — | 4 | 0.25 |\n"
        "| 합계 | 16 | 1.00 | 16 | 1.00 |\n"
        "A군집은 세 종만 있으므로 세 항을 더한다.\n"
        "[eq]%s[/eq]\n"
        "B군집은 네 종이 모두 0.25로 같다.\n"
        "[eq]%s[/eq]" % (lg, la, lb),
        "답) A군집 H′ = %s, B군집 H′ = %s" % (a_val, b_val),
    ]


# 회차별 통일 답. 값은 문제 조건(로그 밑·수치)에 맞춰 그대로 둔다.
