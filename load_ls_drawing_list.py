def main():
    apply_ = '--apply' in sys.argv
    cert = Certification.objects.get(name='조경기사')
    keys = [(y, r) for y, r, *_ in ROWS]
    assert len(keys) == len(set(keys)), '연도·회차 중복'
    new = upd = 0
    for y, r, title, code, rate in ROWS:
        exists = GisaDrawingTask.objects.filter(certification=cert, year=y, round=r).exists()
        new += not exists
        upd += exists
        if apply_:
            GisaDrawingTask.objects.update_or_create(
                certification=cert, year=y, round=r,
                defaults={'title': title, 'code': code, 'pass_rate': rate,
                          'note': NOTES.get((y, r), '')})
    print(f'{cert.name}: {len(ROWS)}회차 (신규 {new}, 갱신 {upd}) · 도면 {len({(t, c) for _, _, t, c, _ in ROWS})}종')
    print('반영 완료' if apply_ else '검사만 했습니다 (--apply 로 반영)')


if __name__ == '__main__':
    main()
