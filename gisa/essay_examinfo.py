def hm(minutes):
    """90 → '1시간 30분', 60 → '1시간', 150 → '2시간 30분'."""
    h, m = divmod(int(minutes), 60)
    if h and m:
        return f'{h}시간 {m}분'
    return f'{h}시간' if h else f'{m}분'
