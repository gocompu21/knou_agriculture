def sync_rounds(text):
    """주제키가 적힌 항목마다 `## N회` 와 `**출제**` 를 DB 값으로 다시 쓴다."""
    pool = list(Certification.objects.filter(name__in=siblings('식물보호기사')))
    lines = text.split('\n')
    fixed = 0
    for i, ln in enumerate(lines):
        m = re.match(r'^\*\*주제키\*\* ([0-9a-f]+)$', ln.strip())
        if not m:
            continue
        key = m.group(1)
        qs = GisaEssayQuestion.objects.filter(certification__in=pool,
                                              source='기출', topic_key=key)
        if not qs.exists():
            print('DB 에 없는 주제키:', key)
            return None, 0
        rounds = sorted({(q.year, q.round) for q in qs}, reverse=True)
        freq = max(q.freq_rounds for q in qs)
        head = next(j for j in range(i, -1, -1) if lines[j].startswith('## '))
        out = next(j for j in range(head, i) if lines[j].startswith('**출제** '))
        new_head = re.sub(r'^## \d+회', '## %d회' % freq, lines[head])
        new_out = '**출제** ' + ' '.join('%d-%d' % r for r in rounds)
        if new_head != lines[head] or new_out != lines[out]:
            fixed += 1
            lines[head], lines[out] = new_head, new_out
    return '\n'.join(lines), fixed


def main():
    apply_ = '--apply' in sys.argv
    note = GisaEssayNote.objects.get(certification__name='식물보호기사', slug='topics')
    text = note.content

    added = [k for k in re.findall(r'^\*\*주제키\*\* ([0-9a-f]+)$', NEW, flags=re.M)
             if k not in text]
    if added:
        text = text.rstrip() + '\n' + NEW.rstrip() + '\n'
    print('정리 글 추가:', len(added), '주제')
    for k in added:
        q = GisaEssayQuestion.objects.filter(topic_key=k).order_by('-year', '-round').first()
        print('  ', k, '|', q.text[:40].replace('\n', ' '))

    text, fixed = sync_rounds(text)
    if text is None:
        return 1
    print('회차 갱신:', fixed, '주제')

    # 제목 파일
    titles = json.load(io.open(TITLES_PATH, encoding='utf-8'))
    new_t = {k: v for k, v in TITLES.items() if titles.get(k) != v}
    for k, v in new_t.items():
        print(f'제목 {"바꿈" if k in titles else "더함"} {k[4:12]} → {v}')
    titles.update(TITLES)

    print(f'\n노트 {len(note.content):,}자 → {len(text):,}자 · 제목 {len(new_t)}건')
    if not apply_:
        print('(검증만 했다. --apply 를 붙여야 반영된다)')
        return 0
    note.content = text
    note.save(update_fields=['content', 'updated_at'])
    json.dump(titles, io.open(TITLES_PATH, 'w', encoding='utf-8'),
              ensure_ascii=False, indent=2)
    print('반영했다.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
