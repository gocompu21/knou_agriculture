def rubric_of(points, pts_list):
    each = round(points / len(pts_list), 2)
    return [{'point': p, 'score': each} for p in pts_list]


def main():
    apply_ = '--apply' in sys.argv
    cert = Certification.objects.get(name=CERT)
    qs = {q.number: q for q in GisaEssayQuestion.objects.filter(
        certification=cert, source='기출', year=YEAR, round=ROUND)}
    print(f'{CERT} {YEAR}-{ROUND} 지금 {len(qs)}문항')

    with transaction.atomic():
        touched_keys = set()
        items = []
        for no, d in sorted(Q.items()):
            q = qs.get(no)
            new = q is None
            if new:
                q = GisaEssayQuestion(certification=cert, source='기출', section='기출',
                                      year=YEAR, round=ROUND, number=no)
            for f in ('qtype', 'text', 'answer_items', 'reference'):
                if f in d:
                    setattr(q, f, d[f])
            if 'answer_items' in d:
                q.answer_text = ''
                q.rubric = []
            if 'notes' in d:
                q.notes = d['notes']
            elif new:
                q.notes = f'{NOTE_B} 산경플랜트 복원본 차례대로 7번부터 붙였다(첫 복원본 6문항 뒤). ' \
                          + d.get('notes_extra', '') + ' [재서술]'
            if new:
                q.topic_group = d['group']
                if d.get('topic'):
                    sib = GisaEssayQuestion.objects.filter(
                        certification=cert, topic_key__startswith=d['topic']).exclude(year=YEAR, round=ROUND).first()
                    q.topic_key = sib.topic_key
                    q.std_major = sib.std_major
                else:
                    q.topic_key = key_of(q.text)
                q.points = BASE[q.qtype]
            elif 'qtype' in d:
                q.points = BASE[q.qtype]
            items.append((q, d, new))
            touched_keys.add(q.topic_key)
            print(f"  {'새' if new else '고침'} {no:2d}. [{q.qtype}] {q.text[:50]}")

        # 배점 — 유형별 기본값에서 회차 합계 45점으로(0.5점 단위, 큰 배점부터)
        allq = [x[0] for x in items]
        for q in qs.values():
            if q.number not in Q:
                allq.append(q)
        pts = {id(q): float(q.points) for q in allq}
        diff = 45.0 - sum(pts.values())
        order = sorted(allq, key=lambda q: (-pts[id(q)], q.number))
        while abs(diff) >= 0.01:
            for q in order:
                if abs(diff) < 0.01:
                    break
                step = 0.5 if diff > 0 else -0.5
                if pts[id(q)] + step >= 1.0:
                    pts[id(q)] += step
                    diff -= step
        for q in allq:
            q.points = pts[id(q)]
        print('  배점:', ' '.join(f'{q.number}:{q.points:g}' for q in sorted(allq, key=lambda q: q.number)),
              '= 합계', sum(pts.values()))

        for q, d, new in items:
            if d.get('rubric_points'):
                q.rubric = rubric_of(float(q.points), d['rubric_points'])
        if not apply_:
            print('검사만 했습니다 (--apply 로 반영)')
            transaction.set_rollback(True)
            return
        for q in allq:
            q.save()

        # 같은 주제의 출제 회차 수·이력을 다시 센다 (tag_essay_frequency 와 같은 꼴)
        for key in touched_keys:
            mem = list(GisaEssayQuestion.objects.filter(certification=cert, topic_key=key))
            rounds = sorted({(m.year, m.round) for m in mem if m.source == '기출' and m.year}, reverse=True)
            note = ' '.join(f'{y}-{r}' for y, r in rounds[:14])
            if len(rounds) > 14:
                note += f' 외 {len(rounds) - 14}'
            for m in mem:
                m.freq_rounds = len(rounds)
                m.freq_note = note[:200]
                m.save(update_fields=['freq_rounds', 'freq_note'])
        n = GisaEssayQuestion.objects.filter(certification=cert, source='기출', year=YEAR, round=ROUND).count()
        print(f'반영 완료 — {YEAR}-{ROUND} {n}문항')


if __name__ == '__main__':
    main()
