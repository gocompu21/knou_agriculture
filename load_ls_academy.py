def main():
    apply = '--apply' in sys.argv
    cert = Certification.objects.get(name=CERT)
    total = sum(q['points'] for q in QUESTIONS)
    print(f'{cert.name} (pk={cert.pk}) 학원예상 {ROUND}회 — {len(QUESTIONS)}문항 {total}점')
    assert total == 40, total
    for q in QUESTIONS:
        exists = GisaEssayQuestion.objects.filter(
            certification=cert, source='학원', year=YEAR, round=ROUND,
            number=q['number']).exists()
        print(f"  {q['number']:>2}. [{q['qtype']}] {q['points']}점 "
              f"{'갱신' if exists else '신규'} · {q['text'][:40]}")
        if not apply:
            continue
        GisaEssayQuestion.objects.update_or_create(
            certification=cert, source='학원', section=SECTION,
            year=YEAR, round=ROUND, number=q['number'],
            defaults={
                'orig_number': q['number'],
                'qtype': q['qtype'],
                'points': q['points'],
                'text': q['text'],
                'answer_items': q['answer_items'],
                'answer_text': q.get('answer_text', ''),
                'reference': q['reference'],
                'rubric': q.get('rubric', []),
            })
    print('반영 완료' if apply else '검사만 했습니다 (--apply 로 반영)')


if __name__ == '__main__':
    main()
