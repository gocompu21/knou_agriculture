def _grid_svg(counts=False):
    """9번 점고법 지반고 그림. counts=True 면 교점마다 걸리는 칸 수를 표시한다."""
    X = [50, 140, 230, 320]          # 30m = 90px
    Y = [60, 120, 180]               # 20m = 60px
    # (i, j, 지반고, 걸리는 칸 수)
    nodes = [
        (0, 0, '9.50', 1), (1, 0, '10.50', 2), (2, 0, '11.00', 1),
        (0, 1, '9.80', 2), (1, 1, '9.50', 4), (2, 1, '10.00', 3), (3, 1, '11.00', 1),
        (0, 2, '10.50', 1), (1, 2, '9.50', 2), (2, 2, '9.80', 2), (3, 2, '10.50', 1),
    ]
    h = 250 if counts else 210
    p = [f'<svg viewBox="0 0 380 {h}" width="380" height="{h}" '
         f'style="max-width:100%;height:auto" xmlns="http://www.w3.org/2000/svg" {_FONT} font-size="12">',
         f'<rect width="380" height="{h}" fill="#fff"/>']
    # 치수선
    p.append('<line x1="50" y1="34" x2="140" y2="34" stroke="#444" stroke-width="1"/>'
             '<line x1="50" y1="28" x2="50" y2="52" stroke="#444" stroke-width="0.8"/>'
             '<line x1="140" y1="28" x2="140" y2="52" stroke="#444" stroke-width="0.8"/>'
             '<circle cx="50" cy="34" r="2" fill="#444"/><circle cx="140" cy="34" r="2" fill="#444"/>'
             '<text x="95" y="27" text-anchor="middle" fill="#222">30</text>')
    p.append('<line x1="24" y1="60" x2="24" y2="120" stroke="#444" stroke-width="1"/>'
             '<line x1="18" y1="60" x2="44" y2="60" stroke="#444" stroke-width="0.8"/>'
             '<line x1="18" y1="120" x2="44" y2="120" stroke="#444" stroke-width="0.8"/>'
             '<circle cx="24" cy="60" r="2" fill="#444"/><circle cx="24" cy="120" r="2" fill="#444"/>'
             '<text x="14" y="94" text-anchor="middle" fill="#222" '
             'transform="rotate(-90 14 90)">20</text>')
    p.append('<text x="360" y="40" text-anchor="end" fill="#222">[단위 : m]</text>')
    # 격자 — 위 2칸, 아래 3칸
    ln = 'stroke="#222" stroke-width="1.6"'
    p.append(f'<line x1="50" y1="60" x2="230" y2="60" {ln}/>'
             f'<line x1="50" y1="120" x2="320" y2="120" {ln}/>'
             f'<line x1="50" y1="180" x2="320" y2="180" {ln}/>'
             f'<line x1="50" y1="60" x2="50" y2="180" {ln}/>'
             f'<line x1="140" y1="60" x2="140" y2="180" {ln}/>'
             f'<line x1="230" y1="60" x2="230" y2="180" {ln}/>'
             f'<line x1="320" y1="120" x2="320" y2="180" {ln}/>')
    color = {1: '#607d8b', 2: '#2e7d32', 3: '#ef6c00', 4: '#c62828'}
    for i, j, val, c in nodes:
        x, y = X[i], Y[j]
        # 지반고 글자는 교점의 오른쪽 아래에 둔다(맨 아랫줄은 선 아래)
        ty = y + 17 if j < 2 else y + 18
        p.append(f'<text x="{x + 5}" y="{ty}" fill="#222">{val}</text>')
        if counts:
            miss = (i, j) == (3, 1)
            p.append(f'<circle cx="{x}" cy="{y}" r="8.5" fill="#fff" stroke="{color[c]}" '
                     f'stroke-width="{2.4 if miss else 1.6}"/>'
                     f'<text x="{x}" y="{y + 4}" text-anchor="middle" font-size="11" '
                     f'font-weight="700" fill="{color[c]}">{c}</text>')
            if miss:
                p.append('<path d="M334 112 C 350 96, 356 80, 346 66" fill="none" '
                         'stroke="#c62828" stroke-width="1.2"/>'
                         '<text x="372" y="60" text-anchor="end" font-size="11" '
                         'fill="#c62828">빠뜨리기 쉬운 모서리</text>')
        else:
            p.append(f'<circle cx="{x}" cy="{y}" r="2" fill="#222"/>')
    if counts:
        lx = 50
        for c, lab in ((1, 'h₁ 모서리'), (2, 'h₂ 두 칸'), (3, 'h₃ 세 칸'), (4, 'h₄ 네 칸')):
            p.append(f'<circle cx="{lx}" cy="226" r="7" fill="#fff" stroke="{color[c]}" '
                     f'stroke-width="1.6"/><text x="{lx}" y="230" text-anchor="middle" '
                     f'font-size="10" font-weight="700" fill="{color[c]}">{c}</text>'
                     f'<text x="{lx + 11}" y="230" font-size="11" fill="#333">{lab}</text>')
            lx += 82
    p.append('</svg>')
    return ''.join(p)


