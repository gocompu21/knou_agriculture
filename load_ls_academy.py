def _contour_svg():
    """2회 2번 — 왼쪽 단면도(표고선과 산 모양), 오른쪽 등고선 평면도."""
    elev = [70, 60, 50, 40, 30, 20]
    ys = {70: 66, 60: 94, 50: 122, 40: 150, 30: 178, 20: 206}
    p = [f'<svg viewBox="0 0 540 250" width="540" height="250" '
         f'style="max-width:100%;height:auto" xmlns="http://www.w3.org/2000/svg" {_FONT} font-size="12">',
         '<rect width="540" height="250" fill="#fff"/>']
    # 단면도 — 표고선, 정상(74m), 높이 4 치수
    for e in elev:
        y = ys[e]
        p.append(f'<line x1="36" y1="{y}" x2="232" y2="{y}" stroke="#222" stroke-width="1"/>'
                 f'<text x="30" y="{y - 3}" text-anchor="end" fill="#222">{e}</text>')
    p.append('<line x1="72" y1="55" x2="170" y2="55" stroke="#222" stroke-width="1"/>'
             '<line x1="68" y1="55" x2="68" y2="66" stroke="#222" stroke-width="1"/>'
             '<line x1="63" y1="55" x2="73" y2="55" stroke="#222" stroke-width="1"/>'
             '<line x1="63" y1="66" x2="73" y2="66" stroke="#222" stroke-width="1"/>'
             '<text x="58" y="64" text-anchor="middle" font-size="11" fill="#222">4</text>')
    # 산 모양 — 꼭짓점 (134,55) 인 포물선
    p.append('<path d="M46 230 Q134 -120 222 230" fill="none" stroke="#222" stroke-width="1.7"/>')
    # 등고선 평면도 — 안쪽일수록 조금 왼쪽으로 치우친 닫힌 곡선
    cy = 128
    rings = [(70, 360, 26, 14), (60, 364, 50, 32), (50, 368, 73, 51),
             (40, 372, 96, 70), (30, 376, 118, 90), (20, 380, 138, 108)]
    import math
    for n, (e, cx, rx, ry) in enumerate(rings, 1):
        p.append(f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="none" '
                 f'stroke="#222" stroke-width="1.6"/>')
        a = math.radians(-8)
        tx, ty = cx + rx * math.cos(a), cy + ry * math.sin(a)
        p.append(f'<text x="{tx + 2:.1f}" y="{ty - 1:.1f}" font-size="11" fill="#222" '
                 f'stroke="#fff" stroke-width="3" paint-order="stroke">{e}</text>')
        b = math.radians(24)
        bx, by = cx + rx * math.cos(b), cy + ry * math.sin(b)
        p.append(f'<text x="{bx - 16:.1f}" y="{by + 4:.1f}" font-size="11" fill="#222" '
                 f'stroke="#fff" stroke-width="3" paint-order="stroke">A{n}</text>')
    p.append('</svg>')
    return ''.join(p)


